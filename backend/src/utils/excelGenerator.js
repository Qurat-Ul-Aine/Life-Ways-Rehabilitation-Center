const BRAND = {
  name: "Life Ways Rehabilitation Centre",
  headerFill: "FF0F2744",
  headerFont: "FFFFFFFF",
  titleFill: "FFEFF6FF",
  sectionFill: "FFECFEFF",
  altFill: "FFF8FAFC",
  border: "FFE2E8F0",
  accent: "FF0D9488",
};

function formatDate(value) {
  if (!value) return "—";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return String(value);
  return d.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
}

function formatDateTime(value) {
  const d = value instanceof Date ? value : new Date(value);
  return d.toLocaleString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

function colLetter(n) {
  let s = "";
  let num = n;
  while (num > 0) {
    const mod = (num - 1) % 26;
    s = String.fromCharCode(65 + mod) + s;
    num = Math.floor((num - 1) / 26);
  }
  return s;
}

function styleHeaderRow(row) {
  row.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND.headerFill } };
    cell.font = { bold: true, color: { argb: BRAND.headerFont }, size: 10 };
    cell.alignment = { vertical: "middle", horizontal: "center", wrapText: true };
    cell.border = {
      top: { style: "thin", color: { argb: BRAND.border } },
      bottom: { style: "thin", color: { argb: BRAND.border } },
      left: { style: "thin", color: { argb: BRAND.border } },
      right: { style: "thin", color: { argb: BRAND.border } },
    };
  });
  row.height = 24;
}

function styleDataRows(sheet, startRow, endRow, colCount) {
  for (let r = startRow; r <= endRow; r += 1) {
    const row = sheet.getRow(r);
    const alt = (r - startRow) % 2 === 1;
    for (let c = 1; c <= colCount; c += 1) {
      const cell = row.getCell(c);
      if (alt) {
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND.altFill } };
      }
      cell.border = {
        top: { style: "thin", color: { argb: BRAND.border } },
        bottom: { style: "thin", color: { argb: BRAND.border } },
        left: { style: "thin", color: { argb: BRAND.border } },
        right: { style: "thin", color: { argb: BRAND.border } },
      };
      cell.alignment = { vertical: "middle", wrapText: true };
      cell.font = { size: 10 };
    }
  }
}

function addContactRows(sheet, meta, startRow, colCount) {
  const lines = [];
  if (meta.address) lines.push(meta.address);
  if (meta.contactPhone) lines.push(`Phone: ${meta.contactPhone}`);
  if (meta.contactEmail) lines.push(`Email: ${meta.contactEmail}`);
  if (!lines.length) return startRow;

  lines.forEach((line) => {
    sheet.mergeCells(startRow, 1, startRow, colCount);
    sheet.getCell(startRow, 1).value = line;
    sheet.getCell(startRow, 1).font = { size: 9 };
    sheet.getCell(startRow, 1).alignment = { horizontal: "center" };
    startRow += 1;
  });
  return startRow;
}

function addReportBanner(sheet, title, type, data, colCount) {
  const meta = data?.exportMeta || {};
  const filters = data?.filters || {};
  const hospital = meta.hospitalName || BRAND.name;

  sheet.mergeCells(1, 1, 1, colCount);
  const orgCell = sheet.getCell(1, 1);
  orgCell.value = hospital;
  orgCell.font = { bold: true, size: 16, color: { argb: BRAND.headerFont } };
  orgCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND.headerFill } };
  orgCell.alignment = { horizontal: "center", vertical: "middle" };
  sheet.getRow(1).height = 30;

  sheet.mergeCells(2, 1, 2, colCount);
  sheet.getCell(2, 1).value = title;
  sheet.getCell(2, 1).font = { bold: true, size: 13 };
  sheet.getCell(2, 1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND.titleFill } };
  sheet.getCell(2, 1).alignment = { horizontal: "center", vertical: "middle" };
  sheet.getRow(2).height = 24;

  let row = 3;
  const generatedAt = meta.generatedAt ? new Date(meta.generatedAt) : new Date();
  sheet.mergeCells(row, 1, row, colCount);
  sheet.getCell(row, 1).value = `Generated: ${formatDateTime(generatedAt)}  |  Report Type: ${titleForType(type)}`;
  sheet.getCell(row, 1).font = { size: 9, italic: true };
  sheet.getCell(row, 1).alignment = { horizontal: "center" };
  row += 1;

  sheet.mergeCells(row, 1, row, colCount);
  sheet.getCell(row, 1).value = `Generated By: ${meta.generatedBy || "System"}`;
  sheet.getCell(row, 1).font = { size: 9 };
  sheet.getCell(row, 1).alignment = { horizontal: "center" };
  row += 1;

  row = addContactRows(sheet, meta, row, colCount);

  const filterLineRows = [];
  if (filters?.from || filters?.to) {
    filterLineRows.push(`Date Range: ${formatDate(filters.from)} — ${formatDate(filters.to)}`);
  }
  if (meta?.filterLabels?.doctor) filterLineRows.push(`Doctor: ${meta.filterLabels.doctor}`);
  else if (filters?.doctorId) filterLineRows.push(`Doctor ID: ${filters.doctorId}`);
  if (meta?.filterLabels?.patient) filterLineRows.push(`Patient: ${meta.filterLabels.patient}`);
  else if (filters?.patientId) filterLineRows.push(`Patient ID: ${filters.patientId}`);

  filterLineRows.forEach((line) => {
    sheet.mergeCells(row, 1, row, colCount);
    sheet.getCell(row, 1).value = line;
    sheet.getCell(row, 1).font = { size: 9 };
    sheet.getCell(row, 1).alignment = { horizontal: "center" };
    row += 1;
  });

  return row + 1;
}

function addSummarySection(sheet, startRow, colCount, items) {
  sheet.mergeCells(startRow, 1, startRow, colCount);
  const titleCell = sheet.getCell(startRow, 1);
  titleCell.value = "Executive Summary";
  titleCell.font = { bold: true, size: 12, color: { argb: "FF0F2744" } };
  titleCell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: BRAND.sectionFill } };
  titleCell.alignment = { horizontal: "center", vertical: "middle" };
  sheet.getRow(startRow).height = 22;

  let row = startRow + 1;
  items.forEach(([label, value]) => {
    sheet.getCell(row, 1).value = label;
    sheet.getCell(row, 1).font = { bold: true, size: 10 };
    sheet.mergeCells(row, 2, row, colCount);
    const valueCell = sheet.getCell(row, 2);
    valueCell.value = value;
    valueCell.alignment = { horizontal: "left", vertical: "middle" };
    if (typeof value === "number" && label.toLowerCase().includes("revenue")) {
      valueCell.numFmt = '"PKR "#,##0';
    }
    row += 1;
  });
  return row + 1;
}

function autoFitColumns(sheet, minWidth = 12, maxWidth = 40) {
  sheet.columns.forEach((col) => {
    let maxLen = minWidth;
    col.eachCell({ includeEmpty: false }, (cell) => {
      const len = String(cell.value ?? "").length;
      if (len > maxLen) maxLen = Math.min(len + 2, maxWidth);
    });
    col.width = maxLen;
  });
}

function finalizeSheet(sheet, headerRow, colCount) {
  if (headerRow > 0) {
    sheet.views = [{ state: "frozen", ySplit: headerRow, activeCell: `A${headerRow + 1}` }];
    if (colCount > 0) {
      sheet.autoFilter = {
        from: { row: headerRow, column: 1 },
        to: { row: headerRow, column: colCount },
      };
    }
  }
}

function addDataTable(sheet, startRow, headers, rows, options = {}) {
  const headerRow = sheet.getRow(startRow);
  headers.forEach((h, i) => {
    headerRow.getCell(i + 1).value = h.label;
  });
  styleHeaderRow(headerRow);

  let rowIdx = startRow + 1;
  rows.forEach((rowData) => {
    const row = sheet.getRow(rowIdx);
    headers.forEach((h, i) => {
      const cell = row.getCell(i + 1);
      cell.value = rowData[h.key] ?? "—";
      if (h.format === "currency") cell.numFmt = '"PKR "#,##0';
      if (h.format === "percent") cell.numFmt = '0.0"%"';
      if (h.format === "date") cell.numFmt = "dd-mmm-yyyy";
      if (h.align) cell.alignment = { horizontal: h.align, vertical: "middle", wrapText: true };
    });
    rowIdx += 1;
  });

  if (rows.length > 0) {
    styleDataRows(sheet, startRow + 1, rowIdx - 1, headers.length);
  }

  if (options.columnWidths) {
    options.columnWidths.forEach((w, i) => {
      sheet.getColumn(i + 1).width = w;
    });
  } else {
    autoFitColumns(sheet);
  }

  if (options.freezeHeader !== false) {
    finalizeSheet(sheet, startRow, headers.length);
  }

  return rowIdx + 1;
}

function addMetricGrid(sheet, startRow, colCount, metrics) {
  sheet.mergeCells(startRow, 1, startRow, colCount);
  sheet.getCell(startRow, 1).value = "Key Statistics";
  sheet.getCell(startRow, 1).font = { bold: true, size: 11, color: { argb: "FF0F2744" } };
  let row = startRow + 1;
  metrics.forEach(([label, value]) => {
    sheet.getCell(row, 1).value = label;
    sheet.getCell(row, 1).font = { bold: true, size: 10 };
    sheet.mergeCells(row, 2, row, colCount);
    sheet.getCell(row, 2).value = value;
    row += 1;
  });
  return row + 1;
}

async function buildTherapyExcel(workbook, data, type) {
  const isDaily = normalizeType(type) === "therapy-daily";
  const s = data.summary || {};
  const periodRows = isDaily ? data.daily || [] : data.monthly || [];

  const execSheet = workbook.addWorksheet("Executive Summary");
  const execStart = addReportBanner(execSheet, titleForType(type), type, data, 2);
  addSummarySection(execSheet, execStart, 2, [
    ["Total Sessions", s.total ?? 0],
    ["Completed Sessions", s.completed ?? 0],
    ["Missed Sessions", s.missed ?? 0],
    ["Cancelled Sessions", s.cancelled ?? 0],
    ["Attendance Rate", Number(s.attendanceRate ?? 0) / 100],
    ["Progress", Number(s.progressPercent ?? 0) / 100],
  ]);
  execSheet.getColumn(1).width = 24;
  execSheet.getColumn(2).width = 20;
  execSheet.getCell(execStart + 5, 2).numFmt = '0.0"%"';
  execSheet.getCell(execStart + 6, 2).numFmt = '0.0"%"';

  const detailSheet = workbook.addWorksheet("Detailed Report");
  const dStart = addReportBanner(detailSheet, isDaily ? "Daily Breakdown" : "Monthly Breakdown", type, data, 7);
  addDataTable(
    detailSheet,
    dStart,
    [
      { label: isDaily ? "Date" : "Month", key: isDaily ? "date" : "month" },
      { label: "Total", key: "total", align: "right" },
      { label: "Completed", key: "completed", align: "right" },
      { label: "Missed", key: "missed", align: "right" },
      { label: "Cancelled", key: "cancelled", align: "right" },
      { label: "Attendance %", key: "attendanceRate", align: "right", format: "percent" },
      { label: "Progress %", key: "progressPercent", align: "right", format: "percent" },
    ],
    periodRows.map((r) => ({
      ...(isDaily ? { date: r.date ? new Date(r.date) : formatDate(r.date) } : { month: r.month }),
      total: r.total ?? 0,
      completed: r.completed ?? 0,
      missed: r.missed ?? 0,
      cancelled: r.cancelled ?? 0,
      attendanceRate: Number(r.attendanceRate ?? 0) / 100,
      progressPercent: Number(r.progressPercent ?? 0) / 100,
    })),
    { columnWidths: [16, 10, 12, 10, 12, 14, 12] }
  );

  const statsSheet = workbook.addWorksheet("Statistics");
  const stStart = addReportBanner(statsSheet, "Period Statistics", type, data, 2);
  const avgAttendance =
    periodRows.length > 0
      ? periodRows.reduce((sum, r) => sum + Number(r.attendanceRate ?? 0), 0) / periodRows.length
      : 0;
  addMetricGrid(statsSheet, stStart, 2, [
    ["Periods Covered", periodRows.length],
    ["Average Attendance", avgAttendance / 100],
    ["Patients in Breakdown", (data.patientBreakdown || []).length],
    ["Highest Completed (single period)", Math.max(...periodRows.map((r) => r.completed ?? 0), 0)],
  ]);
  statsSheet.getCell(stStart + 2, 2).numFmt = '0.0"%"';

  const rawSheet = workbook.addWorksheet("Raw Data");
  const rStart = addReportBanner(rawSheet, "Patient-wise Raw Data", type, data, 8);
  addDataTable(
    rawSheet,
    rStart,
    [
      { label: "Patient", key: "patientName" },
      { label: "Doctor", key: "doctorName" },
      { label: "Total", key: "total", align: "right" },
      { label: "Completed", key: "completed", align: "right" },
      { label: "Missed", key: "missed", align: "right" },
      { label: "Cancelled", key: "cancelled", align: "right" },
      { label: "Progress %", key: "progressPercent", align: "right", format: "percent" },
      { label: "Attendance %", key: "attendanceRate", align: "right", format: "percent" },
    ],
    (data.patientBreakdown || []).map((p) => ({
      patientName: p.patientName,
      doctorName: p.doctorName ?? "—",
      total: p.total ?? 0,
      completed: p.completed ?? 0,
      missed: p.missed ?? 0,
      cancelled: p.cancelled ?? 0,
      progressPercent: Number(p.progressPercent ?? 0) / 100,
      attendanceRate: Number(p.attendanceRate ?? 0) / 100,
    })),
    { columnWidths: [22, 20, 10, 12, 10, 12, 12, 14] }
  );
}

