async function buildProfessionalExcel(type, data) {
  if (!data || data.error) {
    throw new Error(data?.error || "Report data is unavailable.");
  }

  const workbook = new ExcelJS.Workbook();
  workbook.creator = data?.exportMeta?.hospitalName || BRAND.name;
  workbook.created = new Date();
  workbook.modified = new Date();

  const normalized = normalizeType(type);

  switch (normalized) {
    case "therapy-daily":
    case "therapy-monthly":
      await buildTherapyExcel(workbook, data, normalized);
      break;
    case "doctor":
      await buildDoctorExcel(workbook, data);
      break;
    case "patient":
      await buildPatientExcel(workbook, data);
      break;
    case "financial":
      await buildFinancialExcel(workbook, data);
      break;
    default:
      throw new Error(`Unknown report type: ${type}`);
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

